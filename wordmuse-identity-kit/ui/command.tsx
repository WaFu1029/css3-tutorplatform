// Strict case-insensitive substring filter. cmdk's default is fuzzy
// subsequence matching, which surfaces unrelated items (e.g. searching
// "yale" matches any string containing y…a…l…e in order). Substring
// matching keeps results to actual matches.
// A custom filter REPLACES cmdk's built-in keyword handling, so keywords have
// to be matched here too — that is how school shorthand ("mit", "ucla") finds
// an item whose value shares none of those letters. Keyword hits score below
// value hits so a name match still sorts first.
const substringFilter = (value: string, search: string, keywords?: string[]) => {
  const needle = search.toLowerCase()
  if (value.toLowerCase().includes(needle)) return 1
  return keywords?.some((k) => k.toLowerCase().includes(needle)) ? 0.5 : 0
}

function CommandDialog({
  title = "Command Palette",
  description = "Search for a command to run...",
  children,
  className,
  showCloseButton = true,
  filter = substringFilter,
  ...props
}: React.ComponentProps<typeof Dialog> & {
  title?: string
  description?: string
  className?: string
  showCloseButton?: boolean
  filter?: (value: string, search: string, keywords?: string[]) => number
}) {
  return (
    <Dialog {...props}>
      <DialogHeader className="sr-only">
        <DialogTitle>{title}</DialogTitle>
        <DialogDescription>{description}</DialogDescription>
      </DialogHeader>
      <DialogContent
        className={cn("overflow-hidden p-0", className)}
        showCloseButton={showCloseButton}
      >
        <Command filter={filter} className="**:data-[slot=command-input-wrapper]:h-12 [&_[cmdk-group-heading]]:px-2 [&_[cmdk-group-heading]]:font-medium [&_[cmdk-group-heading]]:text-muted-foreground [&_[cmdk-group]]:px-2 [&_[cmdk-group]:not([hidden])_~[cmdk-group]]:pt-0 [&_[cmdk-input-wrapper]_svg]:h-5 [&_[cmdk-input-wrapper]_svg]:w-5 [&_[cmdk-input]]:h-12 [&_[cmdk-item]]:px-2 [&_[cmdk-item]]:py-3 [&_[cmdk-item]_svg]:h-5 [&_[cmdk-item]_svg]:w-5">
          {children}
        </Command>
      </DialogContent>
    </Dialog>
  )
}

